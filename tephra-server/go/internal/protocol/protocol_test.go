func TestChangesResponse(t *testing.T) {
	r, err := ParseChangesResponse([]byte(`{"status":"full-resync-required","latestRevision":4}`))
	if err != nil || r.(ChangesFullResync).LatestRevision != 4 {
		t.Fatalf("%v %v", err, r)
	}
	ok := fmt.Sprintf(`{"status":"ok","fromRevision":0,"toRevision":2,"latestRevision":2,"truncated":false,"changes":[{"fileId":"f","changeType":"delete","path":"A.md","kind":"markdown","revision":2},{"fileId":"f","changeType":"rename","path":"B.md","previousPath":"A.md","blobHash":%q,"size":1,"mtime":2,"kind":"markdown","revision":1}]}`, hashA)
	r, err = ParseChangesResponse([]byte(ok))
	if err != nil || len(r.(ChangesOK).Changes) != 2 {
		t.Fatalf("%v %v", err, r)
	}
	for _, bad := range []string{
		`{"status":"full-resync-required","latestRevision":4,"x":1}`,
		`{"status":"nope"}`,
		`{"status":"ok","fromRevision":0,"toRevision":2,"latestRevision":2,"truncated":false,"changes":[{"fileId":"f","changeType":"create","path":"A.md","kind":"markdown","revision":0}]}`,
		`[]`,
	} {
		if _, err := ParseChangesResponse([]byte(bad)); err == nil {
			t.Errorf("accepted %s", bad)
		}
	}
	b, _ := json.Marshal(NewChangesOK(0, 0, 0, false, nil))
	if string(b) != `{"status":"ok","fromRevision":0,"toRevision":0,"latestRevision":0,"truncated":false,"changes":[]}` {
		t.Fatalf("%s", b)
	}
}

