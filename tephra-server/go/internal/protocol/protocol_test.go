func TestSyncBodyParse(t *testing.T) {
	ok := fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[%s]}`, hashA, entryJSON("f1", "A.md", hashA))
	b, err := ParseSyncPlanBody([]byte(ok))
	if err != nil || b.DeviceID != "d" || len(b.Files) != 1 || b.Files[0].Path != "A.md" {
		t.Fatalf("%v %+v", err, b)
	}
	bad := map[string]string{
		"extra key":     fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[],"x":1}`, hashA),
		"missing":       `{"deviceId":"d","files":[]}`,
		"empty device":  fmt.Sprintf(`{"deviceId":"","manifestHash":%q,"files":[]}`, hashA),
		"bad hash":      `{"deviceId":"d","manifestHash":"zz","files":[]}`,
		"null files":    fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":null}`, hashA),
		"extra entry":   fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":1,"mtime":1,"kind":"markdown","z":1}]}`, hashA, hashA),
		"null mime":     fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":1,"mtime":1,"kind":"markdown","mimeType":null}]}`, hashA, hashA),
		"fraction":      fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":1.5,"mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"negative":      fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":-1,"mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"unsafe":        fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":9007199254740992,"mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"string number": fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":"1","mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"huge":          fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":1e999,"mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"lone surr":     fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"bad-\ud800.md","hash":%q,"size":1,"mtime":1,"kind":"markdown"}]}`, hashA, hashA),
		"trailing":      ok + " {}",
		"not json":      `{`,
		"array":         `[]`,
		"traversal":     fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[%s]}`, hashA, entryJSON("a", "../x.md", hashA)),
	}
	for name, body := range bad {
		if _, err := ParseSyncCommitBody([]byte(body)); err == nil {
			t.Errorf("%s: accepted", name)
		} else if _, ok := err.(*ValidationError); !ok {
			t.Errorf("%s: error type %T", name, err)
		}
	}
	// JS treats 1.0 and 1e2 as integers.
	for _, n := range []string{"1.0", "1e2", "0", "-0", "9007199254740991"} {
		body := fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"A.md","hash":%q,"size":%s,"mtime":1,"kind":"markdown"}]}`, hashA, hashA, n)
		if _, err := ParseSyncPlanBody([]byte(body)); err != nil {
			t.Errorf("number %s rejected: %v", n, err)
		}
	}
	// Valid surrogate pair escape is fine.
	body := fmt.Sprintf(`{"deviceId":"d","manifestHash":%q,"files":[{"fileId":"a","path":"\ud83d\ude00.md","hash":%q,"size":1,"mtime":1,"kind":"markdown"}]}`, hashA, hashA)
	got, err := ParseSyncPlanBody([]byte(body))
	if err != nil || got.Files[0].Path != "😀.md" {
		t.Fatalf("pair: %v %+v", err, got)
	}
	// An escaped backslash before "ud800" is not a surrogate escape.
	if hasLoneSurrogateEscape([]byte(`"\\ud800"`)) {
		t.Fatal("escaped backslash misdetected")
	}
}

func fileJSON() string {
	return fmt.Sprintf(`{"fileId":"file_1","path":"Notes/A.md","blobHash":%q,"size":12,"mtime":1788640000000,"kind":"markdown"}`, hashA)
}

func TestResolveResponse(t *testing.T) {
	for _, match := range []string{"exact", "case", "normalized", "historic"} {
		extra := ""
		if match == "historic" {
			extra = `,"movedFromPath":"Old.md","movedAtRevision":2`
		}
		body := fmt.Sprintf(`{"match":%q,"requestedPath":"Old.md","canonicalPath":"Notes/A.md","file":%s%s}`, match, fileJSON(), extra)
		if _, err := ParseResolveResponse([]byte(body)); err != nil {
			t.Errorf("%s: %v", match, err)
		}
	}
	body := fmt.Sprintf(`{"match":"fuzzy","requestedPath":"A.md","canonicalPath":"A.md","file":%s}`, fileJSON())
	if _, err := ParseResolveResponse([]byte(body)); err == nil {
		t.Fatal("fuzzy accepted")
	}
	body = fmt.Sprintf(`{"match":"exact","requestedPath":"A.md","canonicalPath":"A.md","file":%s,"movedAtRevision":0}`, fileJSON())
	if _, err := ParseResolveResponse([]byte(body)); err == nil {
		t.Fatal("movedAtRevision 0 accepted")
	}
}

func node(id, kind string) string {
	p := id + ".md"
	if kind == "tag" {
		p = strings.TrimPrefix(id, "tag:")
	} else if kind == "unresolved" {
		p = strings.TrimPrefix(id, "unresolved:")
	}
	return fmt.Sprintf(`{"id":%q,"path":%q,"title":null,"kind":%q,"tags":[],"createdAt":0}`, id, p, kind)
}

func TestGraphResponse(t *testing.T) {
	good := `{"revision":7,"truncated":false,"indexPending":true,"nodes":[` + strings.Join([]string{
		node("file_1", "note"), node("file_2", "attachment"), node("tag:x", "tag"), node("unresolved:Missing", "unresolved")}, ",") +
		`],"edges":[{"s":0,"t":1,"count":1,"embeds":1},{"s":0,"t":2,"count":1,"embeds":0},{"s":0,"t":3,"count":2,"embeds":0}]}`
	g, err := ParseGraphResponse([]byte(good))
	if err != nil || len(g.Nodes) != 4 || g.IndexPending == nil || !*g.IndexPending {
		t.Fatalf("%v %+v", err, g)
	}
	bad := map[string]string{
		"oob edge":      `{"revision":1,"truncated":false,"nodes":[` + node("file_1", "note") + `],"edges":[{"s":0,"t":1,"count":1,"embeds":0}]}`,
		"unknown kind":  `{"revision":1,"truncated":false,"nodes":[` + strings.Replace(node("file_1", "note"), `"note"`, `"folder"`, 1) + `],"edges":[]}`,
		"neg embeds":    `{"revision":1,"truncated":false,"nodes":[` + node("a", "note") + `,` + node("b", "note") + `],"edges":[{"s":0,"t":1,"count":1,"embeds":-1}]}`,
		"no truncated":  `{"revision":1,"nodes":[],"edges":[]}`,
		"zero count":    `{"revision":1,"truncated":false,"nodes":[` + node("a", "note") + `,` + node("b", "note") + `],"edges":[{"s":0,"t":1,"count":0,"embeds":0}]}`,
		"missing title": `{"revision":1,"truncated":false,"nodes":[{"id":"a","path":"a","kind":"note","tags":[],"createdAt":0}],"edges":[]}`,
		"empty tag":     `{"revision":1,"truncated":false,"nodes":[{"id":"a","path":"a","title":null,"kind":"note","tags":[""],"createdAt":0}],"edges":[]}`,
		"long id":       `{"revision":1,"truncated":false,"nodes":[{"id":"` + strings.Repeat("a", 1025) + `","path":"a","title":null,"kind":"note","tags":[],"createdAt":0}],"edges":[]}`,
	}
	for name, body := range bad {
		if _, err := ParseGraphResponse([]byte(body)); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
	// max length counts UTF-16 units: 513 astral chars = 1026 units > 1024.
	long := strings.Repeat("\U0001F600", 513)
	body := `{"revision":1,"truncated":false,"nodes":[{"id":"` + long + `","path":"a","title":"t","kind":"note","tags":[],"createdAt":0}],"edges":[]}`
	if _, err := ParseGraphResponse([]byte(body)); err == nil {
		t.Error("UTF-16 length not enforced")
	}
}

