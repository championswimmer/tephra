var (
	hashA = strings.Repeat("a", 64)
	hashB = strings.Repeat("b", 64)
)

func entry(mut func(*SyncManifestEntry)) SyncManifestEntry {
	e := SyncManifestEntry{FileID: "file_1", Path: "Notes/A.md", Hash: hashA, Size: 12, Mtime: 1_788_640_000_000, Kind: "markdown"}
	if mut != nil {
		mut(&e)
	}
	return e
}

func strp(s string) *string { return &s }

func TestCanonicalPathsAccepted(t *testing.T) {
	for _, p := range []string{"Notes.md", "Projects/Alpha.md", "Attachments/image.png"} {
		if !IsCanonicalVaultPath(p) {
			t.Errorf("should accept %q", p)
		}
	}
}

func TestCanonicalPathsRejected(t *testing.T) {
	for _, p := range []string{"", "/Notes.md", "../secret", "a/../../secret", "a//b", "./a", "C:\\foo", "a\x00b",
		"bad-\xed\xa0\x80", "Cafe\u0301.md", "a/", "a/.", "a/b/.."} {
		if IsCanonicalVaultPath(p) {
			t.Errorf("should reject %q", p)
		}
	}
}

func TestNFC(t *testing.T) {
	nfc := "Caf\u00e9.md"
	nfd := norm.NFD.String(nfc)
	if nfd == nfc {
		t.Fatal("expected different forms")
	}
	if !IsCanonicalVaultPath(nfc) || IsCanonicalVaultPath(nfd) {
		t.Fatal("NFC accepted / NFD rejected")
	}
}

func manifestJSON(entries ...string) []byte { return []byte("[" + strings.Join(entries, ",") + "]") }

func entryJSON(fileID, path, hash string) string {
	return fmt.Sprintf(`{"fileId":%q,"path":%q,"hash":%q,"size":1,"mtime":2,"kind":"markdown"}`, fileID, path, hash)
}

func TestManifestRejectsDuplicates(t *testing.T) {
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("file_1", "A.md", hashA), entryJSON("file_2", "A.md", hashB))); err == nil {
		t.Fatal("duplicate path accepted")
	}
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("file_1", "A.md", hashA), entryJSON("file_1", "B.md", hashB))); err == nil {
		t.Fatal("duplicate id accepted")
	}
	if err := ValidateManifest([]SyncManifestEntry{entry(nil), entry(func(e *SyncManifestEntry) { e.Path = "Other.md"; e.Hash = hashB })}, false); err == nil {
		t.Fatal("typed duplicate id accepted")
	}
}

func TestManifestMustBeSorted(t *testing.T) {
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("f1", "B.md", hashA), entryJSON("f2", "A.md", hashA))); err == nil {
		t.Fatal("unsorted accepted")
	}
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("f1", "A.md", hashA), entryJSON("f2", "B.md", hashA))); err != nil {
		t.Fatal(err)
	}
	// code-point order: U+FFFF sorts before U+1F600 (UTF-16 order would not).
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("f1", "\uffff.md", hashA), entryJSON("f2", "\U0001F600.md", hashA))); err != nil {
		t.Fatalf("code point order: %v", err)
	}
	if _, err := ParseSyncManifest(manifestJSON(entryJSON("f1", "\U0001F600.md", hashA), entryJSON("f2", "\uffff.md", hashA))); err == nil {
		t.Fatal("UTF-16 order accepted")
	}
}

